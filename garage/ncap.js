window.ncapFor=function(name,year){
  var hay=String(name||"").toLowerCase();
  var list=window.NCAP||[],best=null,score=0,i,j;
  for(i=0;i<list.length;i++){
    var p=list[i],ok=true;
    for(j=0;j<p.k.length;j++) if(hay.indexOf(p.k[j])<0) ok=false;
    if(!ok)continue;
    var pts=p.k.join("").length;
    if(year&&p.y0&&p.y1){
      if(year>=p.y0&&year<=p.y1)pts+=80;
      else pts-=20;
    }
    if(pts>score){best=p;score=pts}
  }
  if(best&&score>=8) return best;
  if(year&&year<1997) return {stars:0,none:true,old:true,note:"Euro NCAP did not test this era. Crash standards were much weaker."};
  if(year&&year<2009) return {stars:null,none:true,old:true,note:"May have been tested under very old Euro NCAP rules. Stars from that era are not comparable with a modern 5-star."};
  return {stars:null,none:true,note:"No matching Euro NCAP row in our table yet. Check euroncap.com for this exact generation."};
};
window.ncapStars=function(n){
  if(!n) return "Not rated";
  var s="",i; for(i=1;i<=5;i++) s+=i<=n?"\u2605":"\u2606";
  return s;
};
window.ncapExplain=function(r){
  if(!r||r.none) return r&&r.note?r.note:"No Euro NCAP rating on file.";
  var t="Euro NCAP "+r.stars+" star"+(r.stars===1?"":"s")+(r.tested?(" (tested "+r.tested+")"):".");
  if(r.old) t+=" Tested under older rules — not as strict as a 2020s 5-star.";
  else t+=" Adult, child, pedestrian and safety-assist scores sit behind the stars.";
  t+=" Stars compare that generation of car, not every trim. Tap through to the official result if you want the percentages.";
  return t;
};
